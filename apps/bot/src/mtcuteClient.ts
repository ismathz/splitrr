import { join, dirname } from "node:path";
import { TelegramClient } from "@mtcute/node";

import { env } from "./env";
import { createBunSqliteStorage } from "./mtcuteBunStorage";

const CACHE_TTL_MS = 45_000;

let client: TelegramClient | null = null;
const cache = new Map<
  string,
  { members: TelegramGroupMember[]; expires: number }
>();

export type TelegramGroupMember = {
  tgUserId: number;
  name: string;
  /**
   * Telegram's profile-photo placeholder background colors in dark theme
   * (RGB24 ints).
   * Clients typically use 1 color (solid) or 2 colors (gradient).
   */
  avatarBgColors: number[];
  /** True when the user has a public profile photo (Bot API can fetch it). */
  hasPhoto: boolean;
};

let peerProfileColorsBgByColorIdCache:
  | { bgByColorId: Map<number, number[]>; expires: number }
  | null = null;

function sessionStoragePath(): string {
  const dbPath = env.SQLITE_PATH;
  const dir = dirname(dbPath);
  return join(dir, "mtcute.session");
}

function rgb24IntToNumberArray(bgColors: unknown): number[] {
  if (!Array.isArray(bgColors)) return [];
  const out: number[] = [];
  for (const v of bgColors) {
    const n = typeof v === "number" ? v : Number(v);
    if (Number.isFinite(n)) out.push(n);
  }
  return out;
}

async function getPeerProfileBgColorsByColorId(
  tg: TelegramClient,
): Promise<Map<number, number[]>> {
  const now = Date.now();
  if (
    peerProfileColorsBgByColorIdCache &&
    now < peerProfileColorsBgByColorIdCache.expires
  ) {
    return peerProfileColorsBgByColorIdCache.bgByColorId;
  }

  // `help.getPeerProfileColors` returns palettes for profile-photo backgrounds.
  // We specifically prefer `darkColors` so the placeholder matches Telegram dark theme.
  // For IDs 0-6 it may return an autogenerated single-color palette.
  const res = await tg.call({
    _: "help.getPeerProfileColors",
    // Hash used for caching in Telegram servers; any value should work.
    hash: 0
  } as any);

  const options = (res as any)?.colors;
  const bgByColorId = new Map<number, number[]>();

  if (Array.isArray(options)) {
    for (const opt of options) {
      const colorId = opt?.colorId;
      if (typeof colorId !== "number" || !Number.isFinite(colorId)) continue;

      const profileSet = opt?.darkColors ?? opt?.colors;
      const bg = rgb24IntToNumberArray(profileSet?.bgColors);
      const fallback = bg.length ? bg : rgb24IntToNumberArray(profileSet?.paletteColors);
      if (fallback.length) {
        bgByColorId.set(colorId, fallback);
      }
    }
  }

  peerProfileColorsBgByColorIdCache = {
    bgByColorId,
    // This palette list should be stable for a while.
    expires: now + 12 * 60 * 60 * 1000,
  };

  return bgByColorId;
}

async function collectMembers(
  tg: TelegramClient,
  chatId: string,
  type: "all" | "recent"
): Promise<
  Array<{ tgUserId: number; name: string; profileColorId: number; hasPhoto: boolean }>
> {
  const out: Array<{
    tgUserId: number;
    name: string;
    profileColorId: number;
    hasPhoto: boolean;
  }> = [];
  const seenNameLower = new Set<string>();

  for await (const m of tg.iterChatMembers(chatId, {
    type,
    limit: 200
  })) {
    if (m.user.isBot) continue;
    const name = m.user.displayName.trim();
    if (!name) continue;
    const key = name.toLowerCase();
    if (seenNameLower.has(key)) continue;
    seenNameLower.add(key);

    // Prefer profile-color for profile-photo placeholder rendering.
    // Fallback to message/reply color when profile colors are missing.
    const profileColorId =
      m.user.profileColors?.color ?? m.user.color.color;

    out.push({
      tgUserId: m.user.id,
      name,
      profileColorId,
      hasPhoto: m.user.photo != null,
    });
  }
  return out;
}

/**
 * MTProto client (bot token). Used only for `iterChatMembers` — no member rows in SQLite.
 */
export async function initMtcute(): Promise<void> {
  if (client) return;

  const tg = new TelegramClient({
    apiId: env.TELEGRAM_API_ID,
    apiHash: env.TELEGRAM_API_HASH,
    storage: createBunSqliteStorage(sessionStoragePath())
  });

  await tg.start({ botToken: env.TELEGRAM_BOT_TOKEN });
  client = tg;
}

/** Best-effort member display names for a chat (Telegram may cap around 200). */
export async function getSessionMembers(chatId: string): Promise<TelegramGroupMember[]> {
  const hit = cache.get(chatId);
  if (hit && Date.now() < hit.expires) {
    return hit.members;
  }

  if (!client) {
    await initMtcute();
  }
  const tg = client!;

  let rawMembers: Array<{
    tgUserId: number;
    name: string;
    profileColorId: number;
    hasPhoto: boolean;
  }> = [];
  try {
    rawMembers = await collectMembers(tg, chatId, "all");
  } catch {
    try {
      rawMembers = await collectMembers(tg, chatId, "recent");
    } catch {
      rawMembers = [];
    }
  }

  const bgByColorId = await getPeerProfileBgColorsByColorId(tg);

  const members: TelegramGroupMember[] = rawMembers.map((m) => {
    const avatarBgColors = bgByColorId.get(m.profileColorId) ?? [];
    return {
      tgUserId: m.tgUserId,
      name: m.name,
      avatarBgColors,
      hasPhoto: m.hasPhoto,
    };
  });

  cache.set(chatId, { members, expires: Date.now() + CACHE_TTL_MS });
  return members;
}
