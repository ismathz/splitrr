function normalizeForMatch(name: string): string {
  return name
    .toLowerCase()
    .normalize("NFKD")
    .replace(/\p{M}/gu, "")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/** Keyword-based emoji for manual lines and fallback when AI did not set one. */
export function emojiForItemName(name: string): string | null {
  const hay = normalizeForMatch(name);
  if (!hay) return null;

  for (const { match, emoji } of KEYWORD_EMOJIS) {
    if (hay.includes(match)) return emoji;
  }
  return null;
}

const FALLBACK_EMOJI = "🧾";

/**
 * AI-parsed lines may set `item.emoji`; manual lines omit it and use the keyword map.
 */
export function getItemDisplayEmoji(
  item: Pick<Item, "name" | "emoji">,
): string {
  const fromAi = item.emoji?.trim();
  if (fromAi) return fromAi;
  return emojiForItemName(item.name) ?? FALLBACK_EMOJI;
}
